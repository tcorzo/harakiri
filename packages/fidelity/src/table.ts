import type { FidelityView } from "./engine";
import {
  audioOutputs,
  deliveries,
  deliveryRow,
  displays,
  pictureCell,
  pictures,
  soundCell,
  soundTracks,
} from "./scenarios";

const graphemes = new Intl.Segmenter();
const width = (text: string): number => [...graphemes.segment(text)].length;

/** A markdown table with padded columns, as the formatter writes it, so formatting changes nothing. */
function table(head: readonly string[], rows: readonly (readonly string[])[]): string[] {
  const widths = head.map((cell, column) =>
    Math.max(3, width(cell), ...rows.map((r) => width(r[column] ?? "")))
  );

  const line = (cells: readonly string[]) =>
    `| ${cells.map((cell, column) => cell + " ".repeat((widths[column] ?? 0) - width(cell))).join(" | ")} |`;

  return [line(head), line(widths.map((w) => "-".repeat(w))), ...rows.map(line)];
}

const marked = (view: FidelityView): string => {
  const fact = view.facts[0]?.text ?? "";

  return view.downgrades.length === 0 ? fact : `${fact} ⬇`;
};

const why = (view: FidelityView): string =>
  view.downgrades.map((downgrade) => downgrade.message).join(" ") || "None";

/** The compatibility and downgrade tables, produced by running every scenario through the engine. */
export function renderTables(): string {
  const lines = [
    "# Compatibility and downgrades",
    "",
    "Generated by `mise run fidelity:table` from `packages/fidelity`. Do not edit by hand: a test fails when this file and the engine disagree.",
    "",
    "Each cell is what plays. ⬇ marks a downgrade. Sound and picture are decided independently, so each has its own matrix. The scenarios are in `packages/fidelity/src/scenarios.ts`.",
    "",
    "## Sound",
    "",
    ...table(
      ["Track", ...audioOutputs.map((o) => o.name)],
      soundTracks.map((track) => [
        track.label,
        ...audioOutputs.map((output) => marked(soundCell(track, output))),
      ])
    ),
    "",
    "### Why",
    "",
    ...table(
      ["Track", "Output", "Downgrade"],
      soundTracks.flatMap((track) =>
        audioOutputs.flatMap((output) => {
          const view = soundCell(track, output);

          return view.downgrades.length === 0 ? [] : [[track.label, output.name, why(view)]];
        })
      )
    ),
    "",
    "## Picture",
    "",
    ...table(
      ["Picture", ...displays.map((d) => d.name)],
      pictures.map((picture) => [
        picture.label,
        ...displays.map((display) => marked(pictureCell(picture, display))),
      ])
    ),
    "",
    "### Why",
    "",
    ...table(
      ["Picture", "Setup", "Downgrade"],
      pictures.flatMap((picture) =>
        displays.flatMap((display) => {
          const view = pictureCell(picture, display);

          return view.downgrades.length === 0 ? [] : [[picture.label, display.name, why(view)]];
        })
      )
    ),
    "",
    "## Delivery",
    "",
    "On an AV receiver with passthrough on and an HDR display with Vulkan.",
    "",
    ...table(
      ["Delivery", "Plays as", "Downgrades"],
      deliveries.map((delivery) => {
        const view = deliveryRow(delivery);

        return [delivery.name, view.facts.map((f) => f.text).join(" · "), why(view)];
      })
    ),
    "",
  ];

  return lines.join("\n");
}
